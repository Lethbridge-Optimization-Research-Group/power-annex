###############################################################################
# B-newacopf.jl
#
# AC Optimal Power Flow with Chance Constraints
#
# Purpose:
#   1. Solve the normal deterministic AC-OPF.
#   2. Focus on Bus 39.
#   3. Introduce uncertainty at Bus 39.
#   4. Add a chance constraint.
#   5. Compare the results with the deterministic AC-OPF.
###############################################################################


###############################################################################
# 1. LOAD REQUIRED PACKAGES
###############################################################################

# PowerModels:
# Used to read and work with the electrical power-system data.
# JuMP:
# Used to create the optimization model, variables,
# objective function, and constraints.
# Ipopt:
# The optimization solver that will solve our AC-OPF model.

using PowerModels
using JuMP
using Ipopt
using Distributions

###############################################################################
# 2. LOAD THE IEEE 39-BUS TEST CASE
###############################################################################

# Location of the IEEE 39-bus system file.

file_name = "/Users/shidratulmuntaha/power-annex/.github/workflows/cases/case118.m"

# Read the case39.m file.

data = PowerModels.parse_file(file_name)

###############################################################################
# STEP 3: PREPARE THE POWER SYSTEM DATA
###############################################################################

# Convert the generator cost functions into quadratic form.
# This allows us to use the quadratic generation-cost function
# in the OPF objective.

PowerModels.standardize_cost_terms!(data, order=2)

# Calculate thermal limits for the transmission branches.
# These limits are used to prevent transmission lines
# from carrying more power than they can safely handle.

PowerModels.calc_thermal_limits!(data)

# Build the reference data structure.
# This gives us organized access to buses, generators,
# loads, branches, and other network information.

ref = PowerModels.build_ref(data)[:it][:pm][:nw][0]

###############################################################################
# STEP 4: CREATE THE OPTIMIZATION MODEL
###############################################################################

# Create an empty optimization model using JuMP.
#
# We use Ipopt as the solver because AC-OPF is a nonlinear
# optimization problem.

model = Model(Ipopt.Optimizer)

# Tell Ipopt how much information to print while solving.
#
# print_level = 0 means we do not want a lot of solver
# information printed in the terminal.

set_optimizer_attribute(model, "print_level", 0)

###############################################################################
# STEP 5: CREATE VOLTAGE VARIABLES
###############################################################################

# va = voltage angle at each bus.
#
# We create one voltage-angle variable for every bus
# in the IEEE 39-bus system.

@variable(model, va[i in keys(ref[:bus])])


# vm = voltage magnitude at each bus.
#
# Each bus has a minimum and maximum allowed voltage magnitude.
# These limits come from the case39.m data.
#
# start = 1.0 gives the solver an initial value of 1.0
# for the voltage magnitude.

@variable(
    model,
    ref[:bus][i]["vmin"] <= vm[i in keys(ref[:bus])] <= ref[:bus][i]["vmax"],
    start = 1.0
)
###############################################################################
# STEP 6: CREATE GENERATOR VARIABLES
###############################################################################

# pg = active power generated by each generator.
#
# Each generator has a minimum and maximum active-power limit.
# These limits come from the case39.m file.

@variable(
    model,
    ref[:gen][i]["pmin"] <= pg[i in keys(ref[:gen])] <= ref[:gen][i]["pmax"]
)


# qg = reactive power generated by each generator.
#
# Each generator also has a minimum and maximum
# reactive-power limit.

@variable(
    model,
    ref[:gen][i]["qmin"] <= qg[i in keys(ref[:gen])] <= ref[:gen][i]["qmax"]
)
###############################################################################
# STEP 7: CREATE TRANSMISSION-LINE POWER-FLOW VARIABLES
###############################################################################

# p = active power flowing through each transmission line.
#
# The power flow cannot exceed the thermal limit (rate_a)
# of the transmission line.

@variable(
    model,
    -ref[:branch][l]["rate_a"] <= p[(l,i,j) in ref[:arcs]]
    <= ref[:branch][l]["rate_a"]
)


# q = reactive power flowing through each transmission line.
#
# It also has to stay within the transmission-line limit.

@variable(
    model,
    -ref[:branch][l]["rate_a"] <= q[(l,i,j) in ref[:arcs]]
    <= ref[:branch][l]["rate_a"]
)
###############################################################################
# STEP 8: DEFINE THE OBJECTIVE FUNCTION
###############################################################################

# Our goal is to minimize the total cost of electricity generation.
#
# Each generator has a cost function:
#
#     Cost = a*Pg^2 + b*Pg + c
#
# where:
#     Pg = active power generated by the generator
#     a, b, c = cost coefficients from the case39.m file

@objective(
    model,
    Min,

    # Calculate the generation cost for every generator
    # and add all generator costs together.

    sum(
        gen["cost"][1] * pg[i]^2 +
        gen["cost"][2] * pg[i] +
        gen["cost"][3]
        for (i, gen) in ref[:gen]
    )
)
###############################################################################
# STEP 9: FIX THE VOLTAGE ANGLE OF THE REFERENCE BUS
###############################################################################

# The reference bus is used as the angle reference for the
# entire electrical network.
#A reference bus is basically the bus we use as the starting point for voltage angles.

# We set its voltage angle to 0 radians.

for (i, bus) in ref[:ref_buses]

    @constraint(model, va[i] == 0)

end
###########################################################################################################################
# STEP 10: NODAL POWER-BALANCE CONSTRAINTS
###############################################################################

# Store the deterministic active-power constraint for each bus.
active_balance = Dict{Int, ConstraintRef}()

# Go through every bus in the IEEE 39-bus system.
for (i, bus) in ref[:bus]

    # Find all loads connected to the current bus.
    #
    # For example, when i = 39, this gives us
    # the load information connected to Bus 39.

    bus_loads = [ref[:load][l] for l in ref[:bus_loads][i]]


    # Find all shunt elements connected to the current bus.

    bus_shunts = [ref[:shunt][s] for s in ref[:bus_shunts][i]]
    ###############################################################################
# STEP 11: ACTIVE-POWER BALANCE
###############################################################################
# Go through every bus in the system.

# At every bus, the active power must be balanced.
#
# In simple terms:
#
#   Power flowing through the network
#   =
#   Power generated - Power consumed
#
# This equation is applied to every bus.
# Store the deterministic active-power balance for this bus.
active_balance[i] =@constraint(
    model,

    # Active power flowing through transmission lines
    sum(p[a] for a in ref[:bus_arcs][i])

    +

    # Active power flowing through HVDC lines
    sum(p_dc[a_dc] for a_dc in ref[:bus_arcs_dc][i])

    ==

    # Active power generated at this bus
    sum(pg[g] for g in ref[:bus_gens][i])

    -

    # Active power consumed by loads at this bus
    sum(load["pd"] for load in bus_loads)

    -

    # Active power consumed by shunt elements
    sum(shunt["gs"] for shunt in bus_shunts) * vm[i]^2
)
##Power flow=Generation − Demand − Shunt consumption
##Active shunt uses power → subtract.
##reactive shunt contributes reactive power in our equations → add
       
###############################################################################
# STEP 12: REACTIVE-POWER BALANCE
###############################################################################

# At every bus, reactive power must also be balanced.
#
# In simple terms:
#
#   Reactive power flow
#   =
#   Reactive power generated - Reactive power consumed
#
# This equation is applied to every bus.

@constraint(
    model,

    # Reactive power flowing through transmission lines
    sum(q[a] for a in ref[:bus_arcs][i])

    +

    # Reactive power flowing through HVDC lines
    sum(q_dc[a_dc] for a_dc in ref[:bus_arcs_dc][i])

    ==

    # Reactive power generated at this bus
    sum(qg[g] for g in ref[:bus_gens][i])

    -

    # Reactive power consumed by loads at this bus
    sum(load["qd"] for load in bus_loads)

    +

    # Reactive power contribution from shunt elements
    sum(shunt["bs"] for shunt in bus_shunts) * vm[i]^2
)
##Qflow​=QG​−QD​+shunt
end
###############################################################################
# STEP 13: AC POWER-FLOW EQUATIONS FOR TRANSMISSION LINES
###############################################################################

# Go through every transmission branch in the network.

for (i, branch) in ref[:branch]

    # Identify the "from" side of the branch.
    f_idx = (i, branch["f_bus"], branch["t_bus"])

    # Identify the "to" side of the branch.
    t_idx = (i, branch["t_bus"], branch["f_bus"])


    # Get the active and reactive power-flow variables
    # for the two sides of the branch.

    p_fr = p[f_idx]
    q_fr = q[f_idx]

    p_to = p[t_idx]
    q_to = q[t_idx]


    # Get voltage magnitude at the two buses connected
    # by this transmission line.

    vm_fr = vm[branch["f_bus"]]
    vm_to = vm[branch["t_bus"]]


    # Get voltage angle at the two buses.

    va_fr = va[branch["f_bus"]]
    va_to = va[branch["t_bus"]]


    # Calculate the electrical parameters of the branch.

    g, b = PowerModels.calc_branch_y(branch)

    tr, ti = PowerModels.calc_branch_t(branch)


    # Get the shunt parameters of the branch.

    g_fr = branch["g_fr"]
    b_fr = branch["b_fr"]

    g_to = branch["g_to"]
    b_to = branch["b_to"]


    # Square of the transformer tap ratio.

    tm = branch["tap"]^2

###############################################################################
# STEP 14: AC POWER-FLOW EQUATIONS
###############################################################################
##It tells the model how much active power \(P\) and reactive power \(Q\) should flow through each transmission line based on the voltages and voltage angles.

# Active power flowing from the "from" bus.

@constraint(
    model,
    p_fr ==
        (g + g_fr) / tm * vm_fr^2 +
        (-g * tr + b * ti) / tm *
        (vm_fr * vm_to * cos(va_fr - va_to)) +
        (-b * tr - g * ti) / tm *
        (vm_fr * vm_to * sin(va_fr - va_to))
)


# Reactive power flowing from the "from" bus.

@constraint(
    model,
    q_fr ==
        -(b + b_fr) / tm * vm_fr^2 -
        (-b * tr - g * ti) / tm *
        (vm_fr * vm_to * cos(va_fr - va_to)) +
        (-g * tr + b * ti) / tm *
        (vm_fr * vm_to * sin(va_fr - va_to))
)


# Active power flowing into the "to" bus.

@constraint(
    model,
    p_to ==
        (g + g_to) * vm_to^2 +
        (-g * tr - b * ti) / tm *
        (vm_to * vm_fr * cos(va_to - va_fr)) +
        (-b * tr + g * ti) / tm *
        (vm_to * vm_fr * sin(va_to - va_fr))
)


# Reactive power flowing into the "to" bus.

@constraint(
    model,
    q_to ==
        -(b + b_to) * vm_to^2 -
        (-b * tr + g * ti) / tm *
        (vm_to * vm_fr * cos(va_fr - va_to)) +
        (-g * tr - b * ti) / tm *
        (vm_to * vm_fr * sin(va_fr - va_to))
)

###############################################################################
# STEP 15: TRANSMISSION-LINE LIMITS
###############################################################################

# Limit the voltage-angle difference across each transmission line.

@constraint(model, va_fr - va_to <= branch["angmax"])
@constraint(model, va_fr - va_to >= branch["angmin"])


# Limit the apparent power flowing through the transmission line.
# P^2 + Q^2 must not exceed the line's thermal limit.

@constraint(model, p_fr^2 + q_fr^2 <= branch["rate_a"]^2)
@constraint(model, p_to^2 + q_to^2 <= branch["rate_a"]^2)
end
###############################################################################
# STEP 16: SOLVE THE DETERMINISTIC AC-OPF
###############################################################################

# Solve the AC-OPF model using Ipopt.

optimize!(model)

# Show whether the solver successfully solved the problem.

println("The solver termination status is $(termination_status(model))")

# Get and print the minimum generation cost.

cost = objective_value(model)

println("The cost of generation is $(cost).")

##
###############################################################################
# Find buses that have both a generator and a load.Because in our model we define the uncertain quantity as , X=P_G-P_D 

for i in keys(ref[:bus])
    if !isempty(ref[:bus_gens][i]) && !isempty(ref[:bus_loads][i])
        println("Bus $i has both generator and load.")
    end
end

###############################################################################
# STEP 17: CREATE THE UNCERTAINTY DATA DICTIONARY
###############################################################################

# Create a dictionary to store uncertainty information.
#
# The key will be the load ID.
# For each uncertain load, we will store:
#     mu_pd    = mean active-power demand
#     sigma_pd = standard deviation of active-power demand

uncertainty = Dict{Int, Dict{Symbol, Float64}}()
###############################################################################
# STEP 18: GET THE LOAD INFORMATION FROM THE IEEE 118-BUS SYSTEM
###############################################################################

# Go through all loads in the case118 network.
#
# Each load has:
#     load_id  = ID used by PowerModels to identify the load
#     load_bus = bus where the load is connected
#     pd       = active-power demand
#     qd       = reactive-power demand

for (load_id, load) in ref[:load]

    println(
        "Load ID = ", load_id,
        ", Bus = ", load["load_bus"],
        ", Pd = ", load["pd"],
        ", Qd = ", load["qd"]
    )

end
###############################################################################
# STEP 19: IDENTIFY THE UNCERTAIN LOADS
###############################################################################

for (load_id, load) in ref[:load]

    if haskey(uncertainty, load_id)

        println(
            "Load ", load_id,
            " at Bus ", load["load_bus"],
            " is UNCERTAIN."
        )

    else

        println(
            "Load ", load_id,
            " at Bus ", load["load_bus"],
            " is DETERMINISTIC."
        )

    end

end
###############################################################################
# STEP 20: FIND UNCERTAIN LOADS AT EACH BUS
###############################################################################

# Go through every bus in the IEEE 118-bus system.

for (i, bus) in ref[:bus]

    # Get the load IDs connected to this bus.
    bus_load_ids = ref[:bus_loads][i]

    # Check each load connected to this bus.
    for load_id in bus_load_ids

        if haskey(uncertainty, load_id)

            println(
                "Bus ", i,
                " contains uncertain Load ", load_id
            )

        end

    end

end
###############################################################################
# STEP 20: ADD UNCERTAINTY DATA FOR SELECTED LOADS
###############################################################################

# Add the selected uncertain loads to the uncertainty dictionary.
#
# For each load:
#     mu_pd    = mean active-power demand
#     sigma_pd = standard deviation of active-power demand

# Example structure:
#
# uncertainty[load_id] = Dict(
#     :mu_pd    => mean value,
#     :sigma_pd => standard deviation
# )

###############################################################################
# STEP 21: GET THE UNCERTAINTY PARAMETERS
###############################################################################

# Go through every bus in the IEEE 118-bus system.

for (i, bus) in ref[:bus]

    # Get the load IDs connected to this bus.
    bus_load_ids = ref[:bus_loads][i]

    # Check each load connected to the bus.
    for load_id in bus_load_ids

        if haskey(uncertainty, load_id)

            # Get the mean and standard deviation
            # from the uncertainty dictionary.
            μ_Pd = uncertainty[load_id][:mu_pd]
            σ_Pd = uncertainty[load_id][:sigma_pd]

            println(
                "Bus ", i,
                ", Load ", load_id,
                ": μ_Pd = ", μ_Pd,
                ", σ_Pd = ", σ_Pd
            )

        else

            # No uncertainty data for this load.
            # It remains deterministic.
            continue

        end

    end

end
